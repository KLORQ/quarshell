package main

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"path"
	"sort"
	"strings"

	gatewayv1 "github.com/KLORQ/quarshell-proto/gen/go/openshell/gateway/v1"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/descriptorpb"
)

func main() {
	output := flag.String("out", "connect_adapter_generated.go", "output Go source path")
	flag.Parse()
	if err := generate(*output); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(output string) error {
	service := gatewayv1.File_openshell_gateway_v1_openshell_proto.Services().ByName("OpenShell")
	if service == nil {
		return fmt.Errorf("OpenShell service descriptor is missing")
	}
	imports := map[string]string{
		"context":                "context",
		"connectrpc.com/connect": "connect",
		"github.com/KLORQ/quarshell-proto/gen/go/openshell/gateway/v1/gatewayv1connect": "gatewayv1connect",
	}
	for index := 0; index < service.Methods().Len(); index++ {
		method := service.Methods().Get(index)
		for _, message := range []protoreflect.MessageDescriptor{method.Input(), method.Output()} {
			fileOptions := message.ParentFile().Options().(*descriptorpb.FileOptions)
			goPackage := fileOptions.GetGoPackage()
			if goPackage == "" {
				return fmt.Errorf("%s has no go_package option", message.FullName())
			}
			importPath, alias, found := strings.Cut(goPackage, ";")
			if !found {
				alias = path.Base(importPath)
			}
			imports[importPath] = alias
		}
	}

	var source strings.Builder
	source.WriteString("// Code generated by genconnectadapter; DO NOT EDIT.\npackage applicationgrpc\n\nimport (\n")
	importPaths := make([]string, 0, len(imports))
	for importPath := range imports {
		importPaths = append(importPaths, importPath)
	}
	sort.Strings(importPaths)
	for _, importPath := range importPaths {
		fmt.Fprintf(&source, "%s %q\n", imports[importPath], importPath)
	}
	source.WriteString(")\n\ntype OpenShellConnectAdapter struct {\n\tgatewayv1connect.UnimplementedOpenShellHandler\n\tServer *Server\n}\n")

	for index := 0; index < service.Methods().Len(); index++ {
		method := service.Methods().Get(index)
		methodName := string(method.Name())
		input := qualifiedType(method.Input(), imports)
		output := qualifiedType(method.Output(), imports)
		switch {
		case !method.IsStreamingClient() && !method.IsStreamingServer():
			fmt.Fprintf(&source, `
func (a *OpenShellConnectAdapter) %s(ctx context.Context, request *connect.Request[%s]) (*connect.Response[%s], error) {
		response, err := a.Server.%s(ctx, request.Msg)
		if err != nil { return nil, connectError(err) }
		return connect.NewResponse(response), nil
}
`, methodName, input, output, methodName)
		case method.IsStreamingClient() && method.IsStreamingServer():
			fmt.Fprintf(&source, `
func (a *OpenShellConnectAdapter) %s(ctx context.Context, stream *connect.BidiStream[%s, %s]) error {
		return connectError(a.Server.%s(&connectGRPCStream[%s, %s]{ctx: ctx, conn: stream.Conn()}))
}
`, methodName, input, output, methodName, input, output)
		case method.IsStreamingClient():
			fmt.Fprintf(&source, `
func (a *OpenShellConnectAdapter) %s(ctx context.Context, stream *connect.ClientStream[%s]) (*connect.Response[%s], error) {
		adapter := &connectGRPCStream[%s, %s]{ctx: ctx, conn: stream.Conn()}
		err := a.Server.%s(adapter)
		if err != nil { return nil, connectError(err) }
		if adapter.closedResponse == nil { return nil, connectMissingStreamResponse(%q) }
		return connect.NewResponse(adapter.closedResponse), nil
}
`, methodName, input, output, input, output, methodName, methodName)
		case method.IsStreamingServer():
			fmt.Fprintf(&source, `
func (a *OpenShellConnectAdapter) %s(ctx context.Context, request *connect.Request[%s], stream *connect.ServerStream[%s]) error {
		return connectError(a.Server.%s(request.Msg, &connectGRPCStream[%s, %s]{ctx: ctx, conn: stream.Conn()}))
}
`, methodName, input, output, methodName, input, output)
		default:
			return fmt.Errorf("unsupported method stream shape for %s", method.FullName())
		}
	}

	formatted, err := format.Source([]byte(source.String()))
	if err != nil {
		return fmt.Errorf("format Connect adapter: %w", err)
	}
	if err := os.WriteFile(output, formatted, 0o644); err != nil {
		return fmt.Errorf("write Connect adapter: %w", err)
	}
	return nil
}

func qualifiedType(message protoreflect.MessageDescriptor, imports map[string]string) string {
	options := message.ParentFile().Options().(*descriptorpb.FileOptions)
	importPath, alias, found := strings.Cut(options.GetGoPackage(), ";")
	if !found {
		alias = path.Base(importPath)
	}
	return alias + "." + string(message.Name())
}
