#!/usr/bin/env python3
"""Derive a local Go workspace from sibling module manifests, without network access."""
import argparse
import re
from pathlib import Path


def inventory(root):
    modules = {}
    versions = []
    toolchains = []
    dependencies = set()
    for manifest in sorted(root.glob('*/go.mod')):
        text = re.sub(r'//[^\n]*', '', manifest.read_text())
        module = re.search(r'^module\s+(\S+)\s*$', text, re.MULTILINE)
        version = re.search(r'^go\s+(\d+\.\d+(?:\.\d+)?)\s*$', text, re.MULTILINE)
        toolchain = re.search(r'^toolchain\s+go(\d+\.\d+(?:\.\d+)?)\s*$', text, re.MULTILINE)
        if not module or not version:
            raise ValueError(f'invalid module/go directive: {manifest}')
        name = module.group(1)
        if name in modules:
            raise ValueError(f'duplicate module identity: {name}')
        modules[name] = manifest.parent.name
        versions.append(tuple(int(part) for part in version.group(1).split('.')))
        if toolchain:
            toolchains.append(tuple(int(part) for part in toolchain.group(1).split('.')))
        dependencies.update(re.findall(r'^\s*(?:require\s+)?(\S+)\s+(v\S+)', text, re.MULTILINE))
    if not modules:
        raise ValueError('no sibling Go modules found')
    return modules, max(versions), max(toolchains) if toolchains else None, dependencies


def render(modules, version, toolchain, dependencies):
    lines = [f'go {".".join(map(str, version))}']
    if toolchain:
        lines.append(f'toolchain go{".".join(map(str, toolchain))}')
    lines.extend([
        '',
        '// Generated by tools/workspace.py from sibling go.mod files.',
        '// Each module remains an independent Git repository.',
        'use (',
    ])
    lines.extend(f'\t./{directory}' for directory in sorted(modules.values()))
    lines.extend([')', '', 'replace ('])
    lines.extend(f'\t{name} {version} => ./{modules[name]}'
                 for name, version in sorted(dependencies) if name in modules)
    lines.extend([')', ''])
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if go.work needs regeneration')
    parser.add_argument('--modules', action='store_true', help='print module directory names')
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    modules, version, toolchain, dependencies = inventory(root)
    if args.modules:
        print(' '.join(sorted(modules.values())))
        return
    expected = render(modules, version, toolchain, dependencies)
    target = root / 'go.work'
    if args.check:
        if not target.exists() or target.read_text() != expected:
            parser.exit(1, 'go.work is stale; run python3 tools/workspace.py\n')
    else:
        target.write_text(expected)


if __name__ == '__main__':
    main()
